import { execFileSync } from 'node:child_process';
import crypto from 'node:crypto';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

export interface TlsMaterial {
  certPem: string;
  keyPem: string;
  fingerprintSha256: string;
  autoGenerated: boolean;
}

export interface LoadOrGenerateTlsOptions {
  tlsCertPath?: string;
  tlsKeyPath?: string;
  tlsCertPem?: string;
  tlsKeyPem?: string;
  persistDir?: string;
}

export function computeCertFingerprintSha256(certPem: string): string {
  const x509 = new crypto.X509Certificate(certPem);
  return x509.fingerprint256;
}

/**
 * Loads provided TLS cert/key or auto-generates a self-signed ECDSA P-256 certificate
 * via `openssl`, returning PEM material and its SHA-256 fingerprint.
 */
export function loadOrGenerateTlsMaterial(options: LoadOrGenerateTlsOptions = {}): TlsMaterial {
  if (options.tlsCertPem && options.tlsKeyPem) {
    return {
      certPem: options.tlsCertPem,
      keyPem: options.tlsKeyPem,
      fingerprintSha256: computeCertFingerprintSha256(options.tlsCertPem),
      autoGenerated: false
    };
  }

  if (options.tlsCertPath || options.tlsKeyPath) {
    if (!options.tlsCertPath || !options.tlsKeyPath) {
      throw new Error('Both --tls-cert and --tls-key must be provided together.');
    }
    const certPem = fs.readFileSync(options.tlsCertPath, 'utf8');
    const keyPem = fs.readFileSync(options.tlsKeyPath, 'utf8');
    return {
      certPem,
      keyPem,
      fingerprintSha256: computeCertFingerprintSha256(certPem),
      autoGenerated: false
    };
  }

  if (options.persistDir) {
    fs.mkdirSync(options.persistDir, { recursive: true, mode: 0o700 });
    const persistedCertPath = path.join(options.persistDir, 'node-tls.crt');
    const persistedKeyPath = path.join(options.persistDir, 'node-tls.key');

    if (fs.existsSync(persistedCertPath) && fs.existsSync(persistedKeyPath)) {
      const certPem = fs.readFileSync(persistedCertPath, 'utf8');
      const keyPem = fs.readFileSync(persistedKeyPath, 'utf8');
      return {
        certPem,
        keyPem,
        fingerprintSha256: computeCertFingerprintSha256(certPem),
        autoGenerated: false
      };
    }

    generateSelfSignedCertFiles(persistedCertPath, persistedKeyPath);
    const certPem = fs.readFileSync(persistedCertPath, 'utf8');
    const keyPem = fs.readFileSync(persistedKeyPath, 'utf8');
    return {
      certPem,
      keyPem,
      fingerprintSha256: computeCertFingerprintSha256(certPem),
      autoGenerated: true
    };
  }

  const tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), 'bifrost-node-tls-'));
  try {
    const certPath = path.join(tmpDir, 'cert.pem');
    const keyPath = path.join(tmpDir, 'key.pem');
    generateSelfSignedCertFiles(certPath, keyPath);
    const certPem = fs.readFileSync(certPath, 'utf8');
    const keyPem = fs.readFileSync(keyPath, 'utf8');
    return {
      certPem,
      keyPem,
      fingerprintSha256: computeCertFingerprintSha256(certPem),
      autoGenerated: true
    };
  } finally {
    fs.rmSync(tmpDir, { recursive: true, force: true });
  }
}

export function generateSelfSignedCertFiles(certPath: string, keyPath: string): void {
  execFileSync(
    'openssl',
    [
      'req',
      '-x509',
      '-newkey',
      'ec',
      '-pkeyopt',
      'ec_paramgen_curve:prime256v1',
      '-nodes',
      '-days',
      '3650',
      '-subj',
      '/CN=bifrost-egress-node',
      '-keyout',
      keyPath,
      '-out',
      certPath
    ],
    { stdio: ['ignore', 'ignore', 'pipe'] }
  );
  fs.chmodSync(keyPath, 0o600);
  fs.chmodSync(certPath, 0o644);
}
